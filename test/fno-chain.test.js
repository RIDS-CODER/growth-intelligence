test('max pain minimises the total payout, verified against an independent sweep', () => {
  const oi = (K, type) => (type === 'CE' ? Math.max(0, 200 - Math.abs(K - 24200) / 50 * 10)
    : Math.max(0, 200 - Math.abs(K - 23800) / 50 * 10));
  const m = makeChain({ F: 24037, oi, n: 15 });
  const a = CH.analyse({ chain: m.chain, quotes: m.quotes, now: m.now, r: m.r });
  assert.ok(a.maxPain, 'max pain computed');

  // Recompute the payout curve here, from the definition, and confirm the reported strike is the
  // argmin. Reimplementing it in the test is what makes this a check rather than a restatement.
  let best = null, bestPay = Infinity;
  for (const P of m.strikes) {
    let pay = 0;
    for (const K of m.strikes) {
      if (P > K) pay += oi(K, 'CE') * (P - K);
      if (P < K) pay += oi(K, 'PE') * (K - P);
    }
    if (pay < bestPay) { bestPay = pay; best = P; }
  }
  assert.equal(a.maxPain.strike, best, 'max pain agrees with an independent sweep');
  close(a.maxPain.payout, bestPay * m.lotSize, 1, 'payout is in rupees, scaled by the lot size');
  assert.ok(/descriptive only/.test(a.maxPain.caveat), 'it is labelled for what it is');
});

