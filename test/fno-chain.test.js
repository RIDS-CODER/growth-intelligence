/* ============================================================
   F&O INSTRUMENT MASTER AND CHAIN ANALYTICS — tests

   The chain tests work by INVERSION. A synthetic chain is built from a forward and a volatility
   smile that the test chose, every option on it is priced with bs.js, and then the analytics are
   asked to recover the inputs from the prices alone. If the engine hands back the forward and
   the smile that were used to construct the board, the derivation is right — and unlike a
   fixture copied off a screenshot, this can be run at any forward, any expiry and any skew.

   Two things get deliberate abuse:

   STALE LEGS. A real chain always has one. The forward is taken as a median across near-the-money
   strikes precisely so that a single bad quote cannot move the whole surface, so there is a test
   that pushes one leg forty points off and checks the forward does not follow it.

   MISSING DATA. Upstox's F&O master could not be fetched from this sandbox — the proxy 403s it —
   so the parser is written tolerantly and the tests cover the field spellings the existing
   loaders in server.js already accept, plus the failure modes: no lot size, a renamed field, an
   expiry that has passed. What is asserted is not that the live schema matches, but that a
   mismatch is REPORTED rather than silently producing an empty options tab.
   ============================================================ */

const { test } = require('node:test');
const assert = require('node:assert');
const BS = require('../fno/bs');
const CH = require('../fno/chain');
const createInstruments = require('../fno/instruments');

const close = (a, b, tol, msg) => assert.ok(
  Math.abs(a - b) <= tol, `${msg || 'differ'}: got ${a}, expected ${b}, |diff| ${Math.abs(a - b)} > ${tol}`);

const DAY = 86400000;
const NOW = Date.UTC(2026, 8, 15, 6, 0);            // 11:30 IST, a Tuesday
const EXPIRY = Date.UTC(2026, 8, 22);               // a week out

/* ---- the smile the tests will try to recover ----
   A realistic equity-index shape: puts bid over calls, curving up into both wings. */
const flatSmile = () => 0.13;
const skewSmile = (K, F) => {
  const m = Math.log(K / F);
  return 0.13 - 0.35 * m + 2.0 * m * m;
};

/* Build a complete synthetic chain — instrument definitions plus quotes — from a known forward
   and a known smile. Every price is generated by bs.js at the smile's own vol, so put-call
   parity holds exactly and the analytics have a right answer to be measured against. */
function makeChain(opts) {
  const o = opts || {};
  const F = o.F || 24037;
  const expiry = o.expiry || EXPIRY;
  const now = o.now || NOW;
  const r = o.r == null ? 0.065 : o.r;
  const step = o.step || 50;
  const n = o.n || 40;
  const lotSize = o.lotSize || 75;
  const smile = o.smile || (K => skewSmile(K, F));
  /* Spread is PROPORTIONAL, so the mid lands exactly on the theoretical price and the analytics
     have an exact answer to recover. Tick quantisation and empty bids are real and are tested
     separately below — mixing them into every fixture would mean no test could distinguish a
     coding error from the fixture's own rounding. */
  const halfSpreadPct = o.halfSpreadPct == null ? 0.005 : o.halfSpreadPct;
  const tick = o.tick ? 0.05 : 0;
  const oiFor = o.oi || (() => 0);
  const volFor = o.volume || (() => 0);
  const T = BS.yearsToExpiry(now, expiry);

  const centre = Math.round(F / step) * step;
  const strikes = [];
  for (let i = -n; i <= n; i++) strikes.push(centre + i * step);

  const byStrike = {}, quotes = {};
  for (const K of strikes) {
    const iv = smile(K);
    byStrike[K] = { strike: K, CE: null, PE: null };
    for (const type of ['CE', 'PE']) {
      const key = `NSE_FO|${K}${type}`;
      byStrike[K][type] = { key, tradingSymbol: `NIFTY26922${K}${type}`, lotSize, strike: K, type, expiry };
      const px = BS.price(type, F, K, T, iv, r);
      let bid = px * (1 - halfSpreadPct), ask = px * (1 + halfSpreadPct);
      if (tick) {
        bid = Math.round(bid / tick) * tick;
        ask = Math.round(ask / tick) * tick;
        if (bid < tick) { bid = 0; ask = Math.max(tick, ask); }   // an empty bid, as on a real wing
      }
      quotes[key] = { ltp: px, bid, ask, oi: oiFor(K, type), volume: volFor(K, type) };
    }
  }
  return {
    F, T, r, expiry, now, lotSize, strikes, smile,
    chain: {
      underlying: 'NIFTY', name: 'NIFTY 50', exchange: 'NSE',
      expiry, lotSize, strikes, byStrike, strikeStep: step,
      strikeCount: strikes.length, pairedStrikes: strikes.length
    },
    quotes
  };
}

/* ============================================================
   1. THE INSTRUMENT MASTER
   ============================================================ */

/* A master row in the shape the existing server.js loaders expect. */
const row = (o) => ({
  instrument_key: o.key || `NSE_FO|${o.strike || 0}${o.type || 'FUT'}`,
  trading_symbol: o.tsym || 'NIFTY26SEP24000CE',
  asset_symbol: o.asset || 'NIFTY',
  instrument_type: o.type || 'FUT',
  expiry: o.expiry === undefined ? EXPIRY : o.expiry,
  strike_price: o.strike,
  lot_size: o.lot === undefined ? 75 : o.lot,
  tick_size: 0.05,
  segment: 'NSE_FO'
});

function masterFor(strikes, extra) {
  const rows = [];
  for (const k of strikes) {
    rows.push(row({ strike: k, type: 'CE', key: `NSE_FO|${k}CE` }));
    rows.push(row({ strike: k, type: 'PE', key: `NSE_FO|${k}PE` }));
  }
  rows.push(row({ type: 'FUT', key: 'NSE_FO|NIFTYFUT' }));
  return rows.concat(extra || []);
}

const instFrom = (nseRows, bseRows) => createInstruments({
  cacheFile: null, now: () => NOW,
  files: { NSE_FO: nseRows || [], BSE_FO: bseRows || [] }
});

test('the master parses into underlying → expiry → strike, with the lot size taken from the data', () => {
  const I = instFrom(masterFor([23900, 23950, 24000, 24050]));
  const res = I.load();
  return res.then(r => {
    assert.ok(r.available, r.reason);
    const c = I.chain(r.data, 'NIFTY', EXPIRY);
    assert.ok(c, 'the expiry is listed');
    assert.equal(c.lotSize, 75, 'the lot size came from the master, not from a constant');
    assert.deepEqual(c.strikes, [23900, 23950, 24000, 24050], 'strikes are sorted');
    assert.equal(c.strikeStep, 50, 'the strike step is inferred');
    assert.equal(c.pairedStrikes, 4, 'every strike has both legs');
    assert.ok(c.byStrike[24000].CE.key && c.byStrike[24000].PE.key);
    assert.equal(r.data.underlyings.NIFTY.futures.length, 1, 'the futures ladder is kept too');
  });
});

test('no lot size means the contract is DROPPED, never defaulted', () => {
  /* Every position size, margin estimate and rupee of projected P&L scales linearly off the lot
     size. Filling in a plausible-looking default would misstate risk silently and indefinitely —
     the failure mode this whole file is arranged to prevent. */
  return instFrom(masterFor([24000]).concat([
    row({ strike: 24100, type: 'CE', key: 'NSE_FO|24100CE', lot: null }),
    row({ strike: 24100, type: 'PE', key: 'NSE_FO|24100PE', lot: null })
  ])).load().then(r => {
    const c = r.data.underlyings.NIFTY.expiries[0];
    assert.ok(!c.strikes.includes(24100), 'the lot-less strike is not listed');
    assert.ok(r.data.warnings.some(w => /no readable lot size/.test(w)), 'and the drop is reported: ' + JSON.stringify(r.data.warnings));
  });
});

test('two lot sizes inside one expiry raises a warning instead of being picked silently', () => {
  /* This is what a mid-cycle lot-size revision looks like in a master, and quietly choosing one
     would halve or double every position size on that expiry. */
  const rows = masterFor([24000, 24050]).concat([
    row({ strike: 24100, type: 'CE', key: 'NSE_FO|24100CE', lot: 50 }),
    row({ strike: 24100, type: 'PE', key: 'NSE_FO|24100PE', lot: 50 })
  ]);
  return instFrom(rows).load().then(r => {
    assert.ok(r.data.warnings.some(w => /different lot sizes/.test(w)), JSON.stringify(r.data.warnings));
    // It still ships a usable chain, using the most common size.
    assert.equal(r.data.underlyings.NIFTY.expiries[0].lotSize, 75, 'the majority lot size is used');
  });
});

test('a renamed field is reported, not silently swallowed', () => {
  /* The sandbox cannot reach Upstox, so the live schema is unverified. What CAN be guaranteed is
     that a schema change surfaces on the dashboard rather than presenting an empty options tab
     as though the market had no contracts listed. */
  const broken = masterFor([24000]).map(x => {
    const { asset_symbol, ...rest } = x;
    return { ...rest, underlying: asset_symbol };          // a spelling the parser does not know
  });
  return instFrom(broken).load().then(r => {
    assert.equal(r.available, false, 'nothing parsed, so nothing is claimed');
    assert.match(r.reason, /schema has probably changed/i);
  });
});

test('the parser accepts the field spellings the existing server loaders already accept', () => {
  const variants = [
    { instrumentKey: 'X|1', tradingsymbol: 'A', underlying_symbol: 'NIFTY', instrumentType: 'CE', expiry: String(EXPIRY), strikePrice: 24000, lotSize: 75 },
    { instrument_key: 'X|2', name: 'NIFTY', instrument_type: 'PE', expiry_date: '2026-09-22', strike: 24000, lot_size: 75 },
    { instrument_key: 'X|3', asset_symbol: 'NIFTY', option_type: 'CALL', expiry: Math.floor(EXPIRY / 1000), strike_price: 24100, lot_size: 75 }
  ];
  const I = createInstruments({ cacheFile: null, now: () => NOW, files: { NSE_FO: variants, BSE_FO: [] } });
  return I.load().then(r => {
    assert.ok(r.available, r.reason);
    const exps = I.expiries(r.data, 'NIFTY');
    assert.ok(exps.length >= 1, 'contracts were recognised through alternate spellings');
    const all = r.data.underlyings.NIFTY.expiries.flatMap(e => e.strikes);
    assert.ok(all.includes(24000) && all.includes(24100), 'strikes came through: ' + JSON.stringify(all));
  });
});

test('expiry timestamps are read as milliseconds, seconds or a date string', () => {
  const P = createInstruments.__parseExpiry;
  assert.equal(P(EXPIRY), EXPIRY, 'milliseconds pass through');
  assert.equal(P(Math.floor(EXPIRY / 1000)), EXPIRY, 'seconds are scaled up');
  assert.equal(P(String(EXPIRY)), EXPIRY, 'a numeric string is still a number');
  assert.equal(P('2026-09-22'), Date.UTC(2026, 8, 22), 'an ISO date parses');
  assert.equal(P(''), null);
  assert.equal(P(null), null);
  assert.equal(P('not a date'), null);
  assert.equal(P(0), null, 'a zero expiry is missing data, not the epoch');
});

test('expired contracts are filtered out and a minimum life can be required', () => {
  const rows = masterFor([24000])
    .concat(masterFor([24000]).map(x => ({ ...x, instrument_key: x.instrument_key + 'B', expiry: NOW - 2 * DAY })))
    .concat(masterFor([24000]).map(x => ({ ...x, instrument_key: x.instrument_key + 'C', expiry: NOW + 3600000 })));
  const I = instFrom(rows);
  return I.load().then(r => {
    const all = I.expiries(r.data, 'NIFTY');
    assert.ok(all.every(e => e.expiry > NOW), 'nothing already expired is offered');
    assert.ok(all.some(e => e.daysLeft < 1), 'the one expiring in an hour is present by default');

    /* On expiry afternoon the front contract is a different instrument in practice — its Greeks
       are meaningless and its spread is enormous. A caller must be able to skip it. */
    const usable = I.expiries(r.data, 'NIFTY', { minHoursLeft: 6 });
    assert.ok(usable.every(e => e.daysLeft > 0.25), 'the near-dead expiry is excluded on request');
    assert.ok(usable.length < all.length);
  });
});

test('quote keys are windowed around the money rather than requesting the whole board', () => {
  const strikes = []; for (let k = 22000; k <= 26000; k += 50) strikes.push(k);
  const I = instFrom(masterFor(strikes));
  return I.load().then(r => {
    const c = I.chain(r.data, 'NIFTY', EXPIRY);
    assert.equal(I.nearestStrike(c, 24037), 24050, 'the nearest strike to the forward');
    const keys = I.quoteKeys(c, 24037, 10);
    assert.equal(keys.length, 21 * 2, 'ten either side, both legs');
    assert.ok(keys.includes('NSE_FO|24050CE') && keys.includes('NSE_FO|24050PE'));
    assert.ok(!keys.includes('NSE_FO|22000CE'), 'the far wing is not quoted');
    assert.ok(keys.length < strikes.length * 2, 'far fewer than the full board');
  });
});

test('an unreachable master reports unavailable with a reason, never an empty chain', () => {
  const I = createInstruments({
    cacheFile: null, now: () => NOW,
    fetchImpl: async () => { throw new Error('403 from the proxy'); }
  });
  return I.load().then(r => {
    assert.equal(r.available, false);
    assert.ok(/could not download/.test(r.reason), r.reason);
    assert.equal(r.data, null, 'no data is better than invented data');
    assert.deepEqual(I.expiries(null, 'NIFTY'), [], 'accessors tolerate the absence');
    assert.equal(I.chain(null, 'NIFTY', EXPIRY), null);
  });
});

