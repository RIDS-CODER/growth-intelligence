test('the forward is recovered from the chain to within a fraction of a point', () => {
  for (const F of [24037, 52310, 81455]) {
    const m = makeChain({ F, step: F > 50000 ? 100 : 50 });
    const a = CH.analyse({ chain: m.chain, quotes: m.quotes, now: m.now, r: m.r });
    assert.ok(a.ok, a.reason);
    close(a.forward, F, 0.01, `forward at F=${F}`);
    assert.equal(a.forwardDetail.quality, 'tight', 'a clean chain agrees on the forward');
    assert.ok(a.forwardDetail.strikesUsed >= 3, 'several strikes contributed');
  }
});

test('the forward is derived without any spot input at all', () => {
  /* The point of using parity: no dividend yield to guess, no index level to trust. The chain
     bootstraps its own at-the-money from the quotes alone. */
  const m = makeChain({ F: 24037 });
  const a = CH.analyse({ chain: m.chain, quotes: m.quotes, now: m.now, r: m.r });   // no spotHint
  close(a.forward, 24037, 0.01, 'forward with no hint');
  // And supplying a badly wrong hint does not drag it off, because the hint only seeds the band.
  const b = CH.analyse({ chain: m.chain, quotes: m.quotes, now: m.now, r: m.r, spotHint: 23500 });
  close(b.forward, 24037, 0.5, 'forward is not captured by a poor hint');
});

test('one stale leg does not move the forward — the reason it is a median', () => {
  const m = makeChain({ F: 24037 });
  const atmCall = m.chain.byStrike[24050].CE.key;
  const before = CH.analyse({ chain: m.chain, quotes: m.quotes, now: m.now, r: m.r }).forward;

  // A call forty points behind the rest of the board: one leg that has not printed in ten minutes.
  const q = { ...m.quotes };
  q[atmCall] = { ...q[atmCall], ltp: q[atmCall].ltp + 40, bid: q[atmCall].bid + 40, ask: q[atmCall].ask + 40 };
  const after = CH.analyse({ chain: m.chain, quotes: q, now: m.now, r: m.r });

  close(after.forward, before, 1, 'the median absorbs the outlier');
  assert.ok(Math.abs(after.forward - before) < 5, 'and certainly does not follow it forty points');
  // The inconsistency still shows up where it should: in the parity implied-vol gap.
  assert.ok(after.quality.parityIvGap > 0, 'the bad leg is visible in the quality block');
});

test('a chain whose legs disagree is marked suspect rather than reported as fact', () => {
  const m = makeChain({ F: 24037 });
  const q = {};
  // Shift every call up and every put down: parity broken across the board, as in a fast open.
  for (const [k, v] of Object.entries(m.quotes)) {
    const bump = /CE$/.test(k) ? 30 : -30;
    q[k] = { ...v, ltp: Math.max(0.05, v.ltp + bump), bid: Math.max(0.05, v.bid + bump), ask: Math.max(0.1, v.ask + bump) };
  }
  const a = CH.analyse({ chain: m.chain, quotes: q, now: m.now, r: m.r });
  assert.ok(a.ok, 'it still returns something usable');
  assert.ok(a.forwardDetail.dispersionPct > 0, 'dispersion is measured');
  assert.ok(a.quality.warnings.length > 0, 'and the caller is warned');
});

/* ============================================================
   3. THE VOLATILITY SURFACE
   ============================================================ */

test('the implied volatility smile is recovered from the prices', () => {
  const m = makeChain({ F: 24037 });
  const a = CH.analyse({ chain: m.chain, quotes: m.quotes, now: m.now, r: m.r });
  assert.ok(a.surface.length > 20, `expected a populated surface, got ${a.surface.length}`);
  let worst = 0;
  for (const pt of a.surface) {
    const want = m.smile(pt.strike);
    worst = Math.max(worst, Math.abs(pt.iv - want));
  }
  assert.ok(worst < 1e-4, `smile recovered to ${worst.toExponential(2)} — expected better than 1e-4`);
});

test('the surface is built from out-of-the-money options only', () => {
  /* Parity means the in-the-money twin carries no extra information and arrives through a much
     worse quote. Using the OTM side is standard practice and it keeps a stale deep-ITM print
     from manufacturing a vol spike on the wing. */
  const m = makeChain({ F: 24037 });
  const a = CH.analyse({ chain: m.chain, quotes: m.quotes, now: m.now, r: m.r });
  for (const pt of a.surface) {
    if (pt.strike > a.forward) assert.equal(pt.source, 'CE', `strike ${pt.strike} above the forward should use the call`);
    if (pt.strike < a.forward) assert.equal(pt.source, 'PE', `strike ${pt.strike} below the forward should use the put`);
  }
  assert.ok(a.surface.some(p => p.source === 'CE') && a.surface.some(p => p.source === 'PE'), 'both halves are represented');
});

test('at-the-money implied vol is interpolated at the forward, not read off the nearest strike', () => {
  /* With a 50-point strike step the nearest strike can sit 25 points from the forward, and on a
     steep smile that is a real difference. Tested against a deliberately steep one. */
  const F = 24025;                                    // exactly between two strikes
  const steep = K => 0.13 - 1.2 * Math.log(K / F);
  const m = makeChain({ F, smile: steep });
  const a = CH.analyse({ chain: m.chain, quotes: m.quotes, now: m.now, r: m.r });
  close(a.atmIv, 0.13, 2e-3, 'ATM vol at the forward');

  // Reading the nearest strike instead would have been noticeably wrong.
  const nearest = a.surface.find(p => p.strike === a.atmStrike);
  assert.ok(Math.abs(nearest.iv - 0.13) > Math.abs(a.atmIv - 0.13), 'interpolation beats the nearest strike here');
});

test('the expected move comes from the straddle and agrees with the implied vol', () => {
  const m = makeChain({ F: 24000, smile: flatSmile });      // forward on a strike, flat smile
  const a = CH.analyse({ chain: m.chain, quotes: m.quotes, now: m.now, r: m.r });
  assert.equal(a.expectedMove.basis, 'ATM straddle');
  const fromIv = BS.expectedMove(a.forward, a.T, a.atmIv);
  // The straddle and the formula are two routes to the same number.
  assert.ok(Math.abs(a.expectedMove.points - fromIv.points) / fromIv.points < 0.01,
    `straddle ${a.expectedMove.points.toFixed(1)} vs vol-implied ${fromIv.points.toFixed(1)}`);
  /* Sanity on the magnitude, which is the check a relative test cannot make: a week at 13%
     annualised vol is 13% x sqrt(7/365) = 1.8% of a standard deviation, so about 430 points on
     24000, and the MEAN ABSOLUTE move is sqrt(2/pi) of that — around 345. */
  assert.ok(a.expectedMove.points > 250 && a.expectedMove.points < 450, `implausible expected move ${a.expectedMove.points}`);
  close(a.expectedMove.points, 345, 25, 'a week of 13% vol on NIFTY');
  close(a.expectedMove.pct, a.expectedMove.points / a.forward, 1e-9);
});

test('skew is measured at the 25-delta strikes and reads zero on a flat smile', () => {
  const flat = CH.analyse({ ...chainArgs(makeChain({ F: 24037, smile: flatSmile })) });
  assert.ok(flat.skew, 'a 25-delta risk reversal was computed');
  close(flat.skew.rr25, 0, 2e-3, 'a flat smile has no skew');
  close(flat.skew.butterfly25, 0, 2e-3, 'and no curvature');

  /* The 25-delta strikes on a SEVEN-DAY option sit barely 1.2% either side of the money — short
     expiries compress the whole delta ladder into a narrow band — so a skew slope that would
     give several vol points on a quarterly gives under one point here. That is the real number,
     and the assertion below against the constructed smile is what pins it. */
  const skewed = CH.analyse({ ...chainArgs(makeChain({ F: 24037 })) });
  assert.ok(skewed.skew.rr25 > 0.005, `a put-skewed board should price puts over calls, got ${skewed.skew.rr25}`);
  assert.ok(Math.abs(skewed.skew.put25.strike / skewed.forward - 1) < 0.03, 'the 25-delta strikes are close to the money on a weekly');
  assert.ok(skewed.skew.put25.strike < skewed.forward, 'the 25-delta put is below the market');
  assert.ok(skewed.skew.call25.strike > skewed.forward, 'the 25-delta call is above it');
  // The measured risk reversal must match the smile it was built from.
  const wantRR = skewSmile(skewed.skew.put25.strike, 24037) - skewSmile(skewed.skew.call25.strike, 24037);
  close(skewed.skew.rr25, wantRR, 5e-3, 'risk reversal matches the constructed smile');
  // A 0.35 smile slope is a mild bias and must be described as one, not as a panic.
  assert.ok(/normal mild put bias/.test(skewed.skew.reading), skewed.skew.reading);

  // A genuinely steep board reads as one.
  const steep = CH.analyse({ ...chainArgs(makeChain({ F: 24037, smile: K => 0.13 - 1.4 * Math.log(K / 24037) })) });
  assert.ok(/paying up for puts/.test(steep.skew.reading), steep.skew.reading);
  assert.ok(steep.skew.slope > skewed.skew.slope, 'a steeper smile reports a steeper slope');
});

test('skew is normalised so a weekly and a quarterly can be compared on one scale', () => {
  /* The 25-delta band spans 0.46% of the index on a one-day option and 4.58% on a quarterly, so
     the SAME underlying smile produces raw risk reversals an order of magnitude apart. A fixed
     threshold on the raw number would be unreachable on a weekly during a genuine panic and
     would trigger on a quarterly in a dead market. Dividing by atmIv·√T recovers the smile
     slope, which is the quantity that means the same thing at every maturity. */
  const F = 24037;
  const smile = K => 0.13 - 0.9 * Math.log(K / F);
  const results = [];
  for (const days of [7, 30, 90]) {
    const m = makeChain({ F, smile, expiry: NOW + days * DAY, step: 50, n: 90 });
    const a = CH.analyse({ chain: m.chain, quotes: m.quotes, now: m.now, r: m.r });
    assert.ok(a.skew, `${days}d chain produced a skew`);
    results.push({ days, rr25: a.skew.rr25, slope: a.skew.slope, reading: a.skew.reading });
  }
  const fmt = results.map(r => `${r.days}d rr25=${r.rr25.toFixed(4)} slope=${r.slope.toFixed(3)}`).join('  ');

  // The raw risk reversal grows several-fold with maturity...
  assert.ok(results[2].rr25 > results[0].rr25 * 2.5, `raw RR should scale with √T: ${fmt}`);
  // ...while the normalised slope stays put, which is the entire point of normalising.
  for (const r of results) close(r.slope, results[0].slope, 0.15, `normalised slope at ${r.days}d — ${fmt}`);
  // And so every maturity reaches the same verdict about the same market.
  assert.equal(new Set(results.map(r => r.reading)).size, 1, 'one market, one reading: ' + fmt);
});

test('a chain too narrow to reach 25 delta reports no skew rather than a wrong one', () => {
  // Only strikes right around the money — nothing out at 25 delta to measure.
  const m = makeChain({ F: 24037, n: 1 });
  const a = CH.analyse({ chain: m.chain, quotes: m.quotes, now: m.now, r: m.r });
  assert.ok(a.ok);
  assert.equal(a.skew, null, 'no 25-delta strikes listed means no 25-delta skew');
});

