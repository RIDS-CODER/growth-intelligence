test('a zero bid is not treated as half a price', () => {
  /* Far strikes quote 0.00 / 0.05 all day. Treating that as a 0.025 mid feeds a fictional
     premium into the vol surface and is how phantom "cheap" strikes appear. */
  assert.equal(CH.quoteValue({ bid: 0, ask: 0.05 }).src, 'no-bid');
  assert.equal(CH.quoteValue({ bid: 18, ask: 19.5 }).src, 'mid');
  close(CH.quoteValue({ bid: 18, ask: 19.5 }).px, 18.75, 1e-12);
  assert.equal(CH.quoteValue({ ltp: 12 }).src, 'ltp');
  assert.equal(CH.quoteValue({ bid: 0, ask: 0 }), null, 'no quote at all');
  assert.equal(CH.quoteValue(null), null);
  // A no-bid strike is excluded from the forward derivation entirely.
  const m = makeChain({ F: 24037, n: 6 });
  const q = { ...m.quotes };
  for (const k of Object.keys(q)) if (/24[23]\d\dCE/.test(k)) q[k] = { bid: 0, ask: 0.05, ltp: 0.03 };
  const a = CH.analyse({ chain: m.chain, quotes: q, now: m.now, r: m.r });
  close(a.forward, 24037, 1, 'no-bid strikes do not distort the forward');
});

test('calls and puts disagreeing on implied vol is surfaced as a feed problem', () => {
  /* Parity forces a call and a put on the same strike to imply the same volatility. Where they
     do not, one quote is stale — the most direct read available on feed health. */
  const m = makeChain({ F: 24037, n: 10 });
  const clean = CH.analyse({ chain: m.chain, quotes: m.quotes, now: m.now, r: m.r });
  assert.ok(clean.quality.parityIvGap < 1e-4, `a consistent board has no gap, got ${clean.quality.parityIvGap}`);
  assert.equal(clean.quality.parityIvGapNote, null);

  const q = { ...m.quotes };
  for (const k of Object.keys(q)) if (/CE$/.test(k)) q[k] = { ...q[k], bid: q[k].bid * 1.25, ask: q[k].ask * 1.25, ltp: q[k].ltp * 1.25 };
  const bad = CH.analyse({ chain: m.chain, quotes: q, now: m.now, r: m.r });
  assert.ok(bad.quality.parityIvGap > 0.01, `expected a visible gap, got ${bad.quality.parityIvGap}`);
  assert.ok(/put-call parity/.test(bad.quality.parityIvGapNote), bad.quality.parityIvGapNote);
});

