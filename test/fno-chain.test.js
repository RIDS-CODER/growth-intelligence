test('every strike carries Greeks computed at its OWN implied vol', () => {
  /* Using one blended volatility across the board would misprice the wings, which is exactly
     where position sizing goes wrong. Each strike's delta is priced on the smile's value there. */
  const m = makeChain({ F: 24037, n: 12 });
  const a = CH.analyse({ chain: m.chain, quotes: m.quotes, now: m.now, r: m.r });
  for (const row of a.rows) {
    const leg = row.strike >= a.forward ? row.CE : row.PE;
    if (!leg || !leg.iv) continue;
    const want = BS.black76({ type: leg === row.CE ? 'CE' : 'PE', F: a.forward, K: row.strike, T: a.T, sigma: leg.iv, r: a.r });
    close(leg.delta, want.delta, 1e-9, `delta at ${row.strike}`);
    close(leg.vega, want.vega, 1e-6, `vega at ${row.strike}`);
    assert.ok(isFinite(leg.thetaDay) && isFinite(leg.decay1d), 'decay numbers are present');
  }
  /* Delta falls as the strike rises — for calls from +df down to 0, for puts from 0 down to −df.
     The surface interleaves the two, so it is a sawtooth overall and each side must be checked
     on its own. (Asserting a single monotone run across the whole surface would be asserting
     something false about the put wing.) */
  for (const side of ['CE', 'PE']) {
    const pts = a.surface.filter(p => p.source === side);
    for (let i = 1; i < pts.length; i++) {
      assert.ok(pts[i].delta <= pts[i - 1].delta + 1e-9,
        `${side} delta should fall as the strike rises: ${pts[i - 1].strike}→${pts[i - 1].delta}, ${pts[i].strike}→${pts[i].delta}`);
    }
  }
  const calls = a.surface.filter(p => p.source === 'CE');
  const puts = a.surface.filter(p => p.source === 'PE');
  assert.ok(calls.every(p => p.delta > 0) && puts.every(p => p.delta < 0), 'the two wings carry opposite signs');
});

test('tick quantisation and empty bids are handled without corrupting the surface', () => {
  /* The realistic fixture: prices rounded to the 0.05 tick, and far wings quoted 0.00 / 0.05
     with no bid at all. The forward and the at-the-money vol must survive it, and the fabricated
     "half of an offer" price on a no-bid strike must not reach the vol curve. */
  const m = makeChain({ F: 24037, n: 30, tick: true });
  const a = CH.analyse({ chain: m.chain, quotes: m.quotes, now: m.now, r: m.r });
  assert.ok(a.ok, a.reason);
  close(a.forward, 24037, 2, 'the forward survives tick rounding');
  close(a.atmIv, m.smile(a.forward), 0.005, 'at-the-money vol survives it too');

  const noBidStrikes = a.rows.filter(row => {
    const leg = row.strike >= a.forward ? row.CE : row.PE;
    return leg && leg.q && leg.q.src === 'no-bid';
  }).map(r => r.strike);
  assert.ok(noBidStrikes.length > 0, 'the fixture produced some empty bids, as a real wing does');
  for (const k of noBidStrikes) {
    assert.ok(!a.surface.some(p => p.strike === k),
      `strike ${k} has no bid — half of an offer is not a price the market agreed to, so it must not reach the vol surface`);
  }
});

